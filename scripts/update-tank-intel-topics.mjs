// Rebuild the compact editorial references from Wargaming's public source documents.
import {readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
const cached=process.argv.includes('--cached'),sources=[];
async function source(name,url){
  const path=join(tmpdir(),`tank-intel-${name}`);
  const content=cached?await readFile(path,'utf8'):await (async()=>{const response=await fetch(url,{signal:AbortSignal.timeout(30000)});if(!response.ok)throw Error(`${url}: ${response.status}`);const text=await response.text();await writeFile(path,text);return text;})();
  sources.push({url,sha256:createHash('sha256').update(content).digest('hex')});return content;
}
function plain(html){return html.replace(/<[^>]*>/g,' ').replace(/&nbsp;|&#160;/g,' ').replace(/&amp;/g,'&').replace(/&quot;/g,'"').replace(/&#39;|&apos;/g,"'").replace(/\s+/g,' ').trim();}
const yearbooks={};
for(const year of [2020,2021,2022,2023]){
  const url=`https://worldoftanks.com/en/news/general-news/vehicle-yearbook-${year}/`,html=await source(`yearbook-${year}.html`,url);
  const table=html.match(/<table\b[^>]*>([\s\S]*?)<\/table>/i)?.[1];if(!table)throw Error(`Missing ${year} vehicle table`);
  yearbooks[year]={source:url,names:[...table.matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)].map(match=>plain(match[1])).filter(Boolean)};
}
const creatorUrl='https://content-wg.gcdn.co/eu-content/cc-list-converted-090925.json';
const creators=JSON.parse(await source('creators.json',creatorUrl)).map(person=>({name:person.Nickname,language:person.Language,channels:[person.Twitch,person.YouTube,person.Website].filter(Boolean)}));
const result={meta:{sources,creatorSource:'https://worldoftanks.com/en/contributor-directory/',snapshot:'2026-11-28'},creators,yearbooks};
await writeFile(new URL('../games/tank-intel/topics.mjs',import.meta.url),'// Public reference facts; generated by scripts/update-tank-intel-topics.mjs\nexport const TOPICS = '+JSON.stringify(result)+';\n');
console.log(`Topic references: ${creators.length} creators, ${Object.values(yearbooks).reduce((n,year)=>n+year.names.length,0)} yearbook entries`);
